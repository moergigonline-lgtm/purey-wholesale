const fs = require('fs');
function parse(block, prefix, dir) {
  const files = dir ? fs.readdirSync(ROOT + dir) : [];
  return block.trim().split('\n').map((line) => {
    const [n, c, name] = line.split('|');
    const src = dir ? files.find((f) => f.startsWith(n + '-')) : null;
    if (dir && !src) throw new Error('no file for ' + prefix + n);
    return { id: prefix + n, c, n: name.trim(), src: src ? ROOT + dir + src : null, img: dir ? `img/p/${prefix}${n}.webp` : `img/${n}.webp` };
  });
}
